# Sort the CaTCH barcodes by the number of cells in the reference sample and 
# rename them.
full.data <- full.data %>%
             filter_at(vars(-CaTCHBarcode), all_vars(. >= 10)) %>%
             mutate(N = rowMeans(select(., starts_with(ref.treatment)), na.rm = TRUE)) %>%
             arrange(desc(N)) %>%
             mutate(BC_ID = paste("BC", row_number(), sep = "-")) %>%
             dplyr::select(-N)


#### Run DESeq2 to identify over- and underrepresented barcodes ####
cnt.data <- full.data %>%
            column_to_rownames("BC_ID") %>% 
            dplyr::select(-CaTCHBarcode) %>% 
            as.matrix()
cnt.data[is.na(cnt.data)] <- 0

dds <- DESeqDataSetFromMatrix(countData = cnt.data,
                              colData = metadata,
                              design= ~ Treatment)
dds <- DESeq(dds)
results <- list()
plots <- list()
barcodes <- NULL
for (t in setdiff(levels(metadata$Treatment), ref.treatment)) {
  tmp <- results(dds, 
                 alpha = 0.05,
                 contrast = c("Treatment", t, ref.treatment)) %>%
         as_tibble(rownames = NA) %>% 
         rownames_to_column("BC_ID") %>%
         filter(!is.na(padj), padj <= 0.05) %>%
         mutate(Type = if_else(log2FoldChange > 0, "Enriched", "Depleted")) %>%
         arrange(desc(Type), desc(abs(log2FoldChange))) %>%
         inner_join(y = full.data %>% 
                        dplyr::select(BC_ID, starts_with(t), starts_with(ref.treatment)), by = "BC_ID") %>%
         dplyr::select(-baseMean, -lfcSE, -stat, -pvalue, -padj) %>%
         pivot_longer(cols = c(everything(), -BC_ID, -Type, -log2FoldChange), names_to = "Sample", values_to = "CellCount") %>%
         separate(Sample, sep = "_", into = c("Treatment", "Replicate"), remove = FALSE) %>%
         dplyr::select(-Replicate) %>%
         mutate(Treatment = factor(Treatment, levels = treatments),
                CellCount = if_else(is.na(CellCount), 0, CellCount)) %>%
         group_by(BC_ID, Treatment) %>% 
         mutate(CellCount.Mean = mean(CellCount),
                CellCount.SD = sd(CellCount)) %>%
         ungroup() %>%
         mutate(CellCount.Mean = if_else(Type == "Depleted", -CellCount.Mean, CellCount.Mean),
                CellCount.SD = if_else(Type == "Depleted", -CellCount.SD, CellCount.SD),
                BC_ID = factor(BC_ID, levels = unique(BC_ID)))
  
  p <- ggplot(data = tmp, aes(x = BC_ID, y = CellCount.Mean, fill = Treatment)) +
        geom_bar(position = position_dodge(), stat = "identity") + 
        geom_errorbar(aes(ymin = CellCount.Mean - CellCount.SD, 
                          ymax = CellCount.Mean + CellCount.SD), 
                      width = 0.2, position = position_dodge(0.9)) + 
        ggtitle(t) + 
        theme(axis.text.x = element_text(angle = 45, hjust = 1)) + 
        xlab("CaTCH barcode ID") + 
        ylab("Mean cell count")
  
  results[[t]] <- tmp
  plots[[t]] <- p
  barcodes <- c(barcodes, as.character(tmp$BC_ID))
}

