for (i in 1:nrow(metadata)) {
  tmp <- read_delim(file = metadata$Path[i], 
                    col_names = c("CaTCHBarcode", metadata$Sample[i]),
                    col_types = "cd",
                    skip = 1,
                    delim = "\t")
  if (is.null(full.data)) {
    full.data <- tmp
  }
  else {
    full.data <- full.data %>%
                 full_join(y = tmp, by = "CaTCHBarcode")
  }
